	VALUES (QBEP_HTO_MEN.NEXTVAL,'BEFORE_DELETE',:Old.CODNUM,:Old.TITULO,:Old.CUERPO,:Old.FECHA_CREACION,:Old.ESTADO,:Old.UID_USUARIO,:Old.FECHA_ENVIO,:Old.ADJUNTO);
