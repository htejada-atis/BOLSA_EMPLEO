CREATE TRIGGER DBEP_PLO_BRI
BEFORE INSERT
ON TBEP_PLAZAS_OFERTADAS
FOR EACH ROW
DECLARE
BEGIN
    SELECT QBEP_PLO.nextval into :new.CODNUM FROM dual;
    
    INSERT INTO TBEP_HTO_PLAZAS_OFERTADAS (CODCAMBIO,LOG,CODNUM,BEPARE_CODNUM,FECHA_CREACION,FECHA_ABIERTA,FECHA_CERRADA,ESTADO,UID_USUARIO)
    VALUES (QBEP_HTO_PLO.NEXTVAL,'AFTER_INSERT',:New.CODNUM,:New.BEPARE_CODNUM,:New.FECHA_CREACION,:New.FECHA_ABIERTA,:New.FECHA_CERRADA,:New.ESTADO,:New.UID_USUARIO);
END DBEP_PLO_BRI;
--/////////////////////
