BEGIN
	INSERT INTO TBEP_HTO_PLAZAS_OFERTADAS (CODCAMBIO,LOG,CODNUM,BEPARE_CODNUM,FECHA_CREACION,FECHA_ABIERTA,FECHA_CERRADA,ESTADO,UID_USUARIO)
    VALUES (QBEP_HTO_PLO.NEXTVAL,'BEFORE_UPDATE',:Old.CODNUM,:Old.BEPARE_CODNUM,:Old.FECHA_CREACION,:Old.FECHA_ABIERTA,:Old.FECHA_CERRADA,:Old.ESTADO,:Old.UID_USUARIO);
    
 	INSERT INTO TBEP_HTO_PLAZAS_OFERTADAS (CODCAMBIO,LOG,CODNUM,BEPARE_CODNUM,FECHA_CREACION,FECHA_ABIERTA,FECHA_CERRADA,ESTADO,UID_USUARIO)
    VALUES (QBEP_HTO_PLO.NEXTVAL,'AFTER_UPDATE',:New.CODNUM,:New.BEPARE_CODNUM,:New.FECHA_CREACION,:New.FECHA_ABIERTA,:New.FECHA_CERRADA,:New.ESTADO,:New.UID_USUARIO);
END DBEP_PLO_BRU;
