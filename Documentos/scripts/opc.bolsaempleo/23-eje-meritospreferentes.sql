DECLARE
BEGIN
    INSERT INTO TBEP_HTO_MERITOS_PREFERENTES (CODCAMBIO,LOG,CODNUM,CODIGO,DESCRIPCION,TIPO,TIPO_CALCULO,APLICABLE,BASE,FACTOR,VALOR_MAXIMO,BEPITE_TIPO_CODNUM,BEPBLO_APLICABLE_CODNUM,BEPAPA_APLICABLE_CODNUM,BEPITE_APLICABLE_CODNUM,FLGACTIVO)
    VALUES (QBEP_HTO_MEP.NEXTVAL,'BEFORE_DELETE',:Old.CODNUM,:Old.CODIGO,:Old.DESCRIPCION,:Old.TIPO,:Old.TIPO_CALCULO,:Old.APLICABLE,:Old.BASE,:Old.FACTOR,:Old.VALOR_MAXIMO,:Old.BEPITE_TIPO_CODNUM,:Old.BEPBLO_APLICABLE_CODNUM,:Old.BEPAPA_APLICABLE_CODNUM,:Old.BEPITE_APLICABLE_CODNUM,:Old.FLGACTIVO);
END DBEP_MEP_BRD;
